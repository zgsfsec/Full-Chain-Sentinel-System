/**
 * Which contract document describes each WebSocket message.
 *
 * `test/contract/docs.test.ts` reads it to check that every message has exactly
 * one entry and that each document describes the messages listed here. The
 * lists are checked against the real message unions, so a message added to the
 * protocol without a document fails the test.
 */
import type { SentinelClientMessage, SentinelServerMessage } from "../../src/protocol.ts";

export interface Domain {
	/** Document title. */
	readonly title: string;
	/** Browser-to-server messages, in the order the server handles them. */
	readonly client: readonly SentinelClientMessage["type"][];
	/** Server-to-browser messages the document describes. */
	readonly server: readonly SentinelServerMessage["type"][];
}

const domain = (title: string, client: Domain["client"], server: Domain["server"]): Domain => ({
	title,
	client,
	server,
});

