/**
 * Language primitives shared by the browser console and the server.
 *
 * Messages are keyed by their Chinese source text. That keeps call sites
 * readable (`t("保存")`) and makes a missing translation fall back to the
 * source instead of rendering a key. `{name}` placeholders are filled by the
 * caller, so translators can move them without touching code.
 */

export type UiLanguage = "zh" | "en";

export const DEFAULT_UI_LANGUAGE: UiLanguage = "zh";

export function isUiLanguage(value: unknown): value is UiLanguage {
	return value === "zh" || value === "en";
}

export function interpolate(source: string, vars?: Record<string, string | number>): string {
	if (!vars) return source;
	return source.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key: string) =>
		Object.hasOwn(vars, key) ? String(vars[key]) : match,
	);
}

